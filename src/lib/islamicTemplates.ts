export function generateCustomDakwahCaption(topic: string, subAudience = "Muslimah Jambi"): {
  title: string;
  caption: string;
  dalil: { arabic: string; translation: string; source: string };
  hashtags: string[];
} {
  // Check if topic matches preset
  const matched = PRESET_THEMES.find(
    (t) => t.name.toLowerCase().includes(topic.toLowerCase()) || topic.toLowerCase().includes(t.name.toLowerCase())
  );

  if (matched) {
    return {
      title: `${matched.emoji} ${matched.name} | Cahaya Humaira`,
      caption: `${matched.sampleCaption}\n\n${DEFAULT_HASHTAGS.join(" ")}`,
      dalil: matched.dalil,
      hashtags: DEFAULT_HASHTAGS,
    };
  }

  // Synthesize tailored Islamic dakwah caption (~150 words) with warm motherly Jambi tone
  const dalilDb = [
    {
      arabic: "وَمَن يَتَّقِ ٱللَّهَ يَجْعَل لَّهُۥ مَخْرَجًا وَيَرْزُقْهُ مِنْ حَيْثُ لَا يَحْتَسِبُ",
      translation: "Barangsiapa bertakwa kepada Allah niscaya Dia akan membukakan jalan keluar baginya, dan Dia memberinya rezeki dari arah yang tidak disangka-sangkanya.",
      source: "QS. At-Talaq: 2-3",
    },
    {
      arabic: "إِنَّ مَعَ ٱلْعُسْرِ يُسْرًا",
      translation: "Sesungguhnya beserta kesulitan ada kemudahan.",
      source: "QS. Al-Insyirah: 6",
    },
    {
      arabic: "الدُّنْيَا مَتَاعٌ وَخَيْرُ مَتَاعِ الدُّنْيَا الْمَرْأَةُ الصَّالِحَةُ",
      translation: "Dunia adalah perhiasan, dan sebaik-baik perhiasan dunia adalah wanita yang shalihah.",
      source: "HR. Muslim no. 1467",
    },
  ];

  const pickedDalil = dalilDb[Math.floor(Math.random() * dalilDb.length)];

  const synthesizedCaption = `Bismillahirrohmanirrohim... Salam rindu dan peluk sayang dari Umi untuk semua saudariku ${subAudience} nan anggun hatinya.

Hari ini hati Umi tergerak untuk berbincang lembut mengenai "${topic}". Seringkali kita merasa sendiri menapaki liku-liku kehidupan ini. Namun ketahuilah duhai ananda, setiap helai nafas dan tetes peluhmu dalam menjaga ketaatan kepada Allah terhitung sebagai ibadah yang amat mulia di sisi-Nya.

Jangan biarkan riak kekhawatiran dunia mengikis kedamaian di lubuk hatimu. Titipkan semua asa, doa, dan air matamu kepada Allah Azza wa Jalla. Dia Maha Mendengar rintihan hamba-Nya yang bersujud di keheningan sajadah.

Dalil Penyejuk Jiwa:
"${pickedDalil.translation}" (${pickedDalil.source})

Tetaplah berhati lembut, bertutur santun, dan menjadi lentera penyejuk bagi keluargamu tercinta. Semoga keberkahan senantiasa memayungi setiap helai langkahmu hari ini. Aamiin ya Rabbal 'Alamin.`;

  return {
    title: `🌸 Hikmah ${topic} | Renungan Cahaya Humaira`,
    caption: `${synthesizedCaption}\n\n${DEFAULT_HASHTAGS.join(" ")}`,
    dalil: pickedDalil,
    hashtags: DEFAULT_HASHTAGS,
  };
}
